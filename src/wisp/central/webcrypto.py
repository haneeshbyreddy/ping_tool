_RCON = (0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36, 0x6C,
         0xD8, 0xAB, 0x4D)

_BLOCK = 16

CRYPTOJS_ITERATIONS = 999
CRYPTOJS_SALT_LEN = 256


def _xtime(a: int) -> int:
    a <<= 1
    return (a ^ 0x1B) & 0xFF if a & 0x100 else a


def _mul(a: int, b: int) -> int:
    out = 0
    for _ in range(8):
        if b & 1:
            out ^= a
        b >>= 1
        a = _xtime(a)
    return out


def _expand_key(key: bytes) -> tuple[list[list[int]], int]:
    nk = len(key) // 4
    rounds = nk + 6
    words = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (rounds + 1)):
        tmp = list(words[i - 1])
        if i % nk == 0:
            tmp = tmp[1:] + tmp[:1]
            tmp = [_SBOX[b] for b in tmp]
            tmp[0] ^= _RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            tmp = [_SBOX[b] for b in tmp]
        words.append([words[i - nk][j] ^ tmp[j] for j in range(4)])
    return words, rounds


def _encrypt_block(block: bytes, words: list[list[int]], rounds: int) -> bytes:
    state = [list(block[r::4]) for r in range(4)]
    for r in range(4):
        for c in range(4):
            state[r][c] ^= words[c][r]
    for rnd in range(1, rounds + 1):
        for r in range(4):
            for c in range(4):
                state[r][c] = _SBOX[state[r][c]]
        for r in range(1, 4):
            state[r] = state[r][r:] + state[r][:r]
        if rnd != rounds:
            for c in range(4):
                col = [state[r][c] for r in range(4)]
                state[0][c] = _mul(col[0], 2) ^ _mul(col[1], 3) ^ col[2] ^ col[3]
                state[1][c] = col[0] ^ _mul(col[1], 2) ^ _mul(col[2], 3) ^ col[3]
                state[2][c] = col[0] ^ col[1] ^ _mul(col[2], 2) ^ _mul(col[3], 3)
                state[3][c] = _mul(col[0], 3) ^ col[1] ^ col[2] ^ _mul(col[3], 2)
        for r in range(4):
            for c in range(4):
                state[r][c] ^= words[rnd * 4 + c][r]
    return bytes(state[r][c] for c in range(4) for r in range(4))


def aes_cbc_encrypt(key: bytes, iv: bytes, data: bytes) -> bytes:
    if len(key) not in (16, 24, 32):
        raise ValueError("AES key must be 16, 24 or 32 bytes")
    if len(iv) != _BLOCK:
        raise ValueError("AES-CBC iv must be 16 bytes")
    words, rounds = _expand_key(key)
    pad = _BLOCK - (len(data) % _BLOCK)
    data = data + bytes([pad]) * pad
    out = bytearray()
    prev = iv
    for i in range(0, len(data), _BLOCK):
        block = bytes(a ^ b for a, b in zip(data[i:i + _BLOCK], prev))
        prev = _encrypt_block(block, words, rounds)
        out += prev
    return bytes(out)


def cryptojs_encrypt(plaintext: str, passphrase: str, *,
                     iv: bytes | None = None, salt: bytes | None = None,
                     iterations: int = CRYPTOJS_ITERATIONS) -> str:
    iv = iv if iv is not None else os.urandom(_BLOCK)
    salt = salt if salt is not None else os.urandom(CRYPTOJS_SALT_LEN)
    key = hashlib.pbkdf2_hmac("sha512", passphrase.encode("utf-8"), salt,
                              iterations, dklen=32)
    ciphertext = aes_cbc_encrypt(key, iv, plaintext.encode("utf-8"))
    envelope = {
        "ciphertext": base64.b64encode(ciphertext).decode("ascii"),
        "iv": iv.hex(),
        "salt": salt.hex(),
        "iterations": iterations,
    }
    return base64.b64encode(
        json.dumps(envelope).encode("utf-8")).decode("ascii")
